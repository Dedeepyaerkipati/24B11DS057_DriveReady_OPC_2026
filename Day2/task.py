def create_support_ticket(message: str) -> dict:
    """Create a structured support ticket from a student message."""

    prompt = """
    Extract a student support ticket from the message.
    Return ONLY valid JSON with these keys:
    student_name,
    department,
    category,
    issue,
    priority,
    status.

    Use null if student name or department is missing.
    Category must be question, complaint, or request.
    Priority must be low, medium, or high.
    Status must be open.
    Do not invent missing details.
    """

    response = client.chat.completions.create(
        model=MODEL,
        messages=[
            {"role": "system", "content": prompt},
            {"role": "user", "content": message}
        ],
        temperature=0
    )

    raw = response.choices[0].message.content.strip()
    raw = raw.replace("```json", "").replace("```", "").strip()

    return json.loads(raw)

